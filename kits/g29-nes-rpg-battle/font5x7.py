for _k, _v in _G.items():
    assert len(_v) == 7 and all(len(r) == 5 for r in _v), _k

GLYPH = {k: np.array([[c == "#" for c in r] for r in v], bool) for k, v in _G.items()}
ADV = 6  # 5 px glyph + 1 px gap, monospace (tracker columns line up)
GH = 7


def width(s, scale=1):
    return (len(s) * ADV - 1) * scale if s else 0


def mask(s, scale=1):
    """Boolean mask (7*scale, width) of string s; raises on a missing glyph (no silent fallback)."""
    m = np.zeros((GH, max(1, len(s) * ADV - 1)), bool)
    for i, ch in enumerate(s):
        m[:, i * ADV : i * ADV + 5] = GLYPH[ch]
    if scale > 1:
        m = m.repeat(scale, 0).repeat(scale, 1)
    return m
